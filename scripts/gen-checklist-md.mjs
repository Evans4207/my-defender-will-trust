/**
 * Generate docs/LEGAL_REVIEW_CHECKLIST.md from LEGAL_REVIEW_CHECKLIST.docx.
 *
 * WHY
 * ---
 * The .docx is the canonical document and the thing counsel is sent. But GitHub
 * cannot preview a .docx: a reviewer following a link lands on a download button,
 * not the text. Since the whole point of putting the attorneys in the repo was to
 * let them read the checklist and click straight through to each state, that one
 * download step sits right in the middle of the workflow.
 *
 * So this emits a Markdown twin that GitHub renders in place, with every
 * hyperlink live and clickable in the same tab as the state index.
 *
 * THE .DOCX REMAINS CANONICAL. This is a derived view, regenerated by:
 *
 *   npm run checklist:md
 *
 * DO NOT EDIT THE MARKDOWN BY HAND. Two copies of the same document is exactly
 * the setup that produced the stale-link bug (the checklist's own file links sat
 * 20 commits behind reality because a human had to remember to update them). A
 * generated twin cannot drift: edit the .docx, re-run this, commit both.
 *
 * Reads the .docx with `unzip -p` rather than a library on purpose — jszip is
 * only present transitively via `docx`, and a docs script should not depend on
 * another package's dependency tree.
 */

import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOCX = join(ROOT, "docs/LEGAL_REVIEW_CHECKLIST.docx");
const OUT = join(ROOT, "docs/LEGAL_REVIEW_CHECKLIST.md");

const read = (part) =>
  execFileSync("unzip", ["-p", DOCX, part], { maxBuffer: 64 * 1024 * 1024 }).toString("utf8");

const xml = read("word/document.xml");
const rels = read("word/_rels/document.xml.rels");

/** r:id -> external URL, for resolving w:hyperlink. */
const LINKS = Object.fromEntries(
  [...rels.matchAll(/Id="([^"]+)"[^>]*Target="([^"]+)"[^>]*TargetMode="External"/g)].map((m) => [
    m[1],
    m[2],
  ]),
);

const decode = (s) =>
  s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d))
    .replace(/&amp;/g, "&");

/** Escape the few characters that would otherwise be Markdown syntax. */
const esc = (s) => s.replace(/([*_`[\]|])/g, "\\$1");

/**
 * Text of one run, with bold/italic carried across.
 *
 * NOTE the exact `<w:t>`/`<w:t ...>` match: a lazy `<w:t[^>]*>` also matches
 * `<w:tcPr>` and silently swallows table-cell properties as if they were body
 * text. That produced a first draft full of `<w:tcW w:type="dxa"...>`.
 */
function runText(run) {
  const raw = [...run.matchAll(/<w:t(?:\s[^>]*)?>([\s\S]*?)<\/w:t>/g)].map((m) => m[1]).join("");
  if (!raw) return "";
  let t = esc(decode(raw));
  if (!t.trim()) return t;
  const rPr = /<w:rPr>[\s\S]*?<\/w:rPr>/.exec(run)?.[0] ?? "";
  const bold = /<w:b\/>|<w:b\s/.test(rPr);
  const italic = /<w:i\/>|<w:i\s[^>]*w:val="true"/.test(rPr);
  // Preserve surrounding spaces outside the emphasis markers, or Markdown will
  // not render them ("** text**" is literal asterisks).
  const [, lead, core, trail] = /^(\s*)([\s\S]*?)(\s*)$/.exec(t);
  let out = core;
  if (bold) out = `**${out}**`;
  if (italic) out = `*${out}*`;
  return lead + out + trail;
}

/** Largest font size in a paragraph, used to infer heading level (no styles here). */
function maxSize(p) {
  const sizes = [...p.matchAll(/<w:sz w:val="(\d+)"/g)].map((m) => +m[1]);
  return sizes.length ? Math.max(...sizes) : 0;
}

/** Inline content of a paragraph or cell: runs plus resolved hyperlinks. */
function inline(node) {
  let out = "";
  const re = /<w:hyperlink\b[^>]*r:id="([^"]+)"[^>]*>([\s\S]*?)<\/w:hyperlink>|<w:r>([\s\S]*?)<\/w:r>|<w:br\s*\/>|<w:tab\s*\/>/g;
  for (const m of node.matchAll(re)) {
    if (m[1] !== undefined) {
      const label = [...m[2].matchAll(/<w:r>([\s\S]*?)<\/w:r>/g)]
        .map((r) => runText(r[1]))
        .join("")
        .trim();
      const href = LINKS[m[1]];
      out += href ? `[${label || href}](${href})` : label;
    } else if (m[3] !== undefined) {
      out += runText(m[3]);
    } else if (m[0].startsWith("<w:br")) {
      out += "<br/>";
    } else {
      out += " ";
    }
  }
  return out.replace(/[ \t]+/g, " ").trim();
}

function paragraph(p) {
  const text = inline(p);
  if (!text) return "";
  const sz = maxSize(p);
  // Direct formatting only — size is the sole signal of hierarchy in this file.
  if (sz >= 28) return `# ${text.replace(/\*\*/g, "")}\n`;
  if (sz >= 24) return `## ${text.replace(/\*\*/g, "")}\n`;
  if (sz >= 21) return `### ${text.replace(/\*\*/g, "")}\n`;
  if (sz === 20) return `*${text}*\n`;
  return `${text}\n`;
}

function table(tbl) {
  const rows = [...tbl.matchAll(/<w:tr\b[^>]*>([\s\S]*?)<\/w:tr>/g)].map((r) => r[1]);
  if (!rows.length) return "";
  const cells = (row) =>
    [...row.matchAll(/<w:tc>([\s\S]*?)<\/w:tc>/g)].map((c) =>
      // A cell may hold several paragraphs; join them so nothing is dropped, and
      // neutralise pipes so they cannot break out of the Markdown table.
      [...c[1].matchAll(/<w:p\b[^>]*>([\s\S]*?)<\/w:p>/g)]
        .map((p) => inline(p[1]))
        .filter(Boolean)
        .join("<br/>")
        .replace(/\|/g, "\\|"),
    );
  // The .docx sets nearly every table run bold, which is fine at 8.5pt in Word
  // but renders as a wall of bold on screen. Because the bold is UNIFORM it
  // carries no signal, so dropping it loses nothing — except in the first column,
  // where keeping the item id bold (A1, B4 …) is what makes the table scannable.
  // Emphasis markers are the only unescaped asterisks: esc() turns a literal "*"
  // into "\*", so this cannot damage real content.
  const unbold = (r) => r.map((c, i) => (i === 0 ? c : c.replace(/\*\*/g, "")));

  const head = cells(rows[0]);
  const body = rows.slice(1).map((r) => unbold(cells(r)));
  const width = Math.max(head.length, ...body.map((r) => r.length));
  const pad = (r) => [...r, ...Array(width - r.length).fill("")];
  return [
    `| ${pad(head).join(" | ")} |`,
    `|${" --- |".repeat(width)}`,
    ...body.map((r) => `| ${pad(r).join(" | ")} |`),
  ].join("\n") + "\n";
}

// Walk the body in document order so tables stay attached to their section.
const body = /<w:body>([\s\S]*)<\/w:body>/.exec(xml)[1];
const parts = [];
for (const m of body.matchAll(/<w:tbl>([\s\S]*?)<\/w:tbl>|<w:p\b[^>]*>([\s\S]*?)<\/w:p>/g)) {
  parts.push(m[1] !== undefined ? table(m[1]) : paragraph(m[2]));
}

const banner = `<!--
  GENERATED FILE — DO NOT EDIT.
  Rendered from docs/LEGAL_REVIEW_CHECKLIST.docx by scripts/gen-checklist-md.mjs.
  The .docx is canonical and is what counsel is sent. Edit that, then run:
      npm run checklist:md
-->

> **This is the web-readable copy** of the legal review checklist, so it can be
> read here without downloading anything and every link below is clickable.
> The Word version — [\`LEGAL_REVIEW_CHECKLIST.docx\`](LEGAL_REVIEW_CHECKLIST.docx) —
> is the canonical document and the one to annotate if you prefer to comment in Word.
>
> Working state by state? Start with the
> [**state-by-state review index**](STATE_REVIEW_INDEX.md) — every jurisdiction with
> a live link to its own official statute.

---

`;

const md = (banner + parts.filter((s) => s.trim()).join("\n")).replace(/\n{3,}/g, "\n\n");

/**
 * `--check` regenerates and compares instead of writing, so CI (or a human before
 * sending a packet) can prove the Markdown twin still matches the .docx. Without
 * this, editing the .docx and forgetting to re-run leaves counsel reading a stale
 * copy — the precise failure the hand-pinned links already caused once.
 */
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== md) {
    console.error(
      `${OUT} is OUT OF DATE with the .docx.\n` +
        `The Word document has changed since the Markdown was generated.\n` +
        `Run: npm run checklist:md`,
    );
    process.exit(1);
  }
  console.log(`${OUT} is up to date with the .docx`);
  process.exit(0);
}

writeFileSync(OUT, md);

const linkCount = (md.match(/\]\(https?:/g) ?? []).length;
console.log(`wrote ${OUT}`);
console.log(`  ${parts.length} blocks, ${linkCount} live links, ${md.length} chars`);
if (linkCount < Object.keys(LINKS).length) {
  console.warn(
    `  WARNING: the .docx defines ${Object.keys(LINKS).length} external links but only ` +
      `${linkCount} made it into the Markdown — some hyperlink markup was not matched.`,
  );
  process.exit(1);
}
